import assert from 'node:assert/strict';
import fs from 'node:fs';
import {parseRecipeImport,importCounts,importPageHtml} from '../src/bulk-import.js';
import {ingredients} from '../src/recipes.js';
const raw=fs.readFileSync(new URL('../data/recipe-starter-pack.json',import.meta.url),'utf8');
const rows=parseRecipeImport(raw,ingredients,[]);
assert.equal(rows.length,8);
assert.deepEqual(importCounts(rows),{ready:8,duplicate:0,invalid:0});
for(const row of rows){
 assert.equal(row.recipe.published,false);
 assert.equal(row.recipe.public_photo_path,null);
 assert(row.recipe.ingredients.length>=5);
 assert(row.recipe.steps.length>=3);
 assert(row.recipe.title_it.length>3);
 assert(row.recipe.description_it.length>10);
}
assert.equal(rows.filter(row=>row.recipe.cuisine==='Lebanese').length,4);
const duplicate=parseRecipeImport(raw,ingredients,['mujaddara-rice-lentils']);
assert.equal(duplicate[0].status,'duplicate');
assert.equal(duplicate[1].status,'ready');
const modified=JSON.parse(raw);
modified.recipes[0].published=true;
modified.recipes[0].public_photo_path='hijacked';
modified.recipes[0].admin_role=true;
modified.recipes[1].ingredients[0].id='not_a_real_ingredient';
modified.recipes[2].slug=modified.recipes[0].slug;
const amended=parseRecipeImport(JSON.stringify(modified),ingredients,[]);
assert.equal(amended[0].recipe.published,false);
assert.equal(amended[0].recipe.public_photo_path,null);
assert.equal(amended[0].recipe.admin_role,undefined);
assert.equal(amended[1].status,'invalid');
assert.equal(amended[2].status,'invalid');
assert.throws(()=>parseRecipeImport('{',ingredients,[]),/Invalid JSON/);
assert.throws(()=>parseRecipeImport(JSON.stringify({version:1,recipes:Array(26).fill(modified.recipes[0])}),ingredients,[]),/1–25/);
assert.throws(()=>parseRecipeImport('x'.repeat(400001),ingredients,[]),/400 KB/);
const html=importPageHtml({lang:'en',rows:rows,selected:new Set([0,1]),results:null,loading:false,link:(url,label)=>`<a href="${url}">${label}</a>`});
assert.match(html,/recipe-bulk-import-form/);
assert.match(html,/Mujaddara/);
assert.match(html,/checked/);
assert.match(html,/Import selected as drafts/);
assert.match(html,/private drafts/);
const italian=importPageHtml({lang:'it',rows:rows,selected:new Set(),results:null,loading:false,link:(url,label)=>`<a href="${url}">${label}</a>`});
assert.match(italian,/Importazione ricette/);
assert.match(italian,/disab|bozz/);
console.log('PASS v9: 8 bilingual drafts, ingredient validation, duplicate protection, privilege stripping, 25-item/400KB limits, UI translations.');
