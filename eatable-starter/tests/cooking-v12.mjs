import assert from 'node:assert/strict';
import {cookText,clampCookingStep,recipeFingerprint,readCookingProgress,writeCookingProgress,clearCookingProgress} from '../src/cooking-mode.js';
const m=new Map();
const storage={getItem:k=>m.has(k)?m.get(k):null,setItem:(k,v)=>m.set(k,v),removeItem:k=>m.delete(k)};
const dish={id:'batata-harra',steps:[{en:'Cut potatoes',it:'Taglia le patate'},{en:'Roast potatoes',it:'Arrostisci le patate'},{en:'Season and serve',it:'Condisci e servi'}]};
assert.equal(readCookingProgress(dish,storage),null);
writeCookingProgress(dish,1,storage);
assert.equal(readCookingProgress(dish,storage),1,'step 2 resumes');
writeCookingProgress(dish,20,storage);
assert.equal(readCookingProgress(dish,storage),2,'step clamps to last');
writeCookingProgress(dish,-2,storage);
assert.equal(readCookingProgress(dish,storage),null,'step zero is a fresh start, not resume');
writeCookingProgress(dish,1,storage);
const edited={...dish,steps:[{en:'Cut potatoes',it:'Taglia le patate'},{en:'Bake slowly',it:'Arrostisci le patate'},{en:'Season and serve',it:'Condisci e servi'}]};
assert.notEqual(recipeFingerprint(edited),recipeFingerprint(dish));
assert.equal(readCookingProgress(edited,storage),null,'recipe edits invalidate stale progress');
clearCookingProgress(dish,storage);
assert.equal(readCookingProgress(dish,storage),null,'finishing clears progress');
assert.equal(readCookingProgress({id:'single',steps:['one']},storage),null);
assert.equal(clampCookingStep(NaN,3),0);
assert.equal(clampCookingStep(2,2),1);
assert.equal(cookText('it','resume'),'Riprendi la preparazione');
assert.equal(cookText('en','textSize'),'Larger text');
console.log('v12 cooking mode unit tests: PASS');
