import assert from 'node:assert/strict';
import {curatedEditorHtml,curatedListHtml,validateCurated} from '../src/curated-editor.js';
import {curatedFromDb} from '../src/discovery.js';
import {validatePhoto} from '../src/photo-cloud.js';

const vocab=[{id:'potato',name:{en:'Potato',it:'Patate'}},{id:'garlic',name:{en:'Garlic',it:'Aglio'}}];
const cuisines=[{id:'Lebanese',name:{en:'Lebanese',it:'Libanese'},flag:'🇱🇧'}];
const link=(slug,text)=>`<a href="/${slug}">${text}</a>`;
const base={slug:'batata-harra',title_en:'Batata Harra',title_it:'Patate piccanti libanesi',description_en:'Traditional Lebanese potatoes with coriander and garlic.',description_it:'Patate libanesi con coriandolo fresco e aglio.',cuisine:'Lebanese',category:'Mezze',diet:'vegan',prep_minutes:40,servings:4,ingredients:[{id:'potato',qty:600,unit:'g'}],steps:[{en:'Roast the potatoes.',it:'Arrostisci le patate.'}],emoji:'🥔',theme:'green',published:true};
const args={lang:'en',vocabulary:vocab,cuisines,link,getPublicUrl:p=>'https://example.invalid/'+p};
const newHtml=curatedEditorHtml({...args,recipe:null});
assert.match(newHtml,/id="curated-photo-input"/);
assert.match(newHtml,/accept="image\/jpeg,image\/png,image\/webp"/);
assert.match(newHtml,/value="publish"/);
const draftHtml=curatedEditorHtml({...args,recipe:{...base,published:false,photo_path:'user/uuid/uuid.jpg',public_photo_path:null}});
assert.match(draftHtml,/data-action="curated-preview-private"/);
assert.doesNotMatch(draftHtml,/example.invalid/);
const publicHtml=curatedEditorHtml({...args,recipe:{...base,public_photo_path:'curated/batata-harra/photo.jpg'}});
assert.match(publicHtml,/https:\/\/example.invalid\/curated\/batata-harra\/photo.jpg/);
assert.match(publicHtml,/name="remove_photo"/);
const list=curatedListHtml({lang:'en',recipes:[base,{...base,slug:'other',public_photo_path:'img.png'}],link});
assert.match(list,/With photos/);
assert.match(list,/Needs a cover photo/);
const recipe=curatedFromDb({...base,public_photo_path:'curated/batata-harra/image.jpg'});
assert.equal(recipe.public_photo_path,'curated/batata-harra/image.jpg');
assert.equal(validateCurated({...base},vocab),'');
assert.equal(validatePhoto({size:5*1024*1024,type:'image/jpeg'}),'jpg');
assert.throws(()=>validatePhoto({size:5*1024*1024+1,type:'image/jpeg'}));
assert.throws(()=>validatePhoto({size:100,type:'image/gif'}));
console.log('PASS: v7 template rendering, private draft preview, public photo, serialization rules and image constraints.');
